import type {
  AuditLogEntry,
  BroadcastAudience,
  InAppNotification,
  ConversationSummary,
  DirectMessage,
  MessageContact,
  NotificationHistoryFilter,
  NotificationHistoryRow,
  SupportCategoryAdmin,
  SupportTicket,
  SupportTicketCategory,
  TicketStatusChange,
  SystemSetting,
  TicketReply,
} from "./support.types";

/** A well-formed request the support data does not allow (mapped to 422 / 409). */
export class SupportRuleError extends Error {
  constructor(
    readonly code: string,
    message: string,
    readonly status: 403 | 409 | 422 = 422,
  ) {
    super(message);
    this.name = "SupportRuleError";
  }
}

export type TicketStatusValue = "open" | "in_progress" | "resolved" | "closed";

/**
 * Ids are BIGINT / INT identities generated by the database. A non-numeric id
 * finds nothing (lookups) or throws RecordNotFoundError (writes). Missing
 * references (category, recipient, assignee) throw SupportRuleError.
 */
export interface SupportRepository {
  // Categories
  getActiveCategories(): Promise<SupportTicketCategory[]>;

  // COM-010 student <-> Admin messaging (NXA_Messages). Only a student and an active Admin / Super Admin
  // may exchange messages; SupportRuleError MESSAGING_NOT_ALLOWED (403) otherwise.
  /** Active Admins and Super Admins a student may write to. */
  listMessageContacts(): Promise<MessageContact[]>;
  listConversations(userId: string): Promise<ConversationSummary[]>;
  /** Messages between the two users, oldest first. */
  getConversation(userId: string, otherUserId: string): Promise<DirectMessage[]>;
  /** With `audit` (a staff send), the message and its SEND_MESSAGE audit row (ids only, no text) are one transaction. */
  sendMessage(senderUserId: string, recipientUserId: string, body: string, audit: boolean): Promise<DirectMessage>;
  /** Marks the messages from `otherUserId` to `userId` as read; returns how many changed (0 = nothing written). */
  markConversationRead(userId: string, otherUserId: string): Promise<number>;

  // SUP-006 category management (no delete: tickets reference categories; deactivate instead).
  getAllCategories(): Promise<SupportCategoryAdmin[]>;
  /** SupportRuleError CATEGORY_EXISTS (409) for a duplicate name. Audited with the insert. */
  createCategory(name: string, actorUserId: string): Promise<SupportCategoryAdmin>;
  /** RecordNotFoundError for an unknown id; an unchanged save writes nothing and is not audited. */
  updateCategory(id: string, changes: { name?: string | undefined; isActive?: boolean | undefined }, actorUserId: string): Promise<{ category: SupportCategoryAdmin; changed: boolean }>;

  /** SUP-005: every status change of a ticket, oldest first. RecordNotFoundError for an unknown ticket. */
  getTicketStatusHistory(ticketId: string): Promise<TicketStatusChange[]>;

  /** COM-008: notifications across all recipients, newest first, paged on the server. */
  getNotificationHistory(filter: NotificationHistoryFilter): Promise<{ rows: NotificationHistoryRow[]; total: number }>;

  // Tickets
  /**
   * Inserts the ticket (and its first status-history row) in one transaction.
   * The category must exist and be active. Throws DuplicateRecordError when
   * the ticket number is taken.
   */
  createTicket(ticket: Omit<SupportTicket, "id" | "createdAt" | "replies">): Promise<SupportTicket>;
  getTicketById(id: string): Promise<SupportTicket | null>;
  getTicketsByStudent(studentUserId: string): Promise<SupportTicket[]>;
  getAllTickets(filter?: { status?: string; category?: string }): Promise<SupportTicket[]>;
  /**
   * Changes status and/or assignee with a status-history row and an audit
   * record in one transaction. An unchanged status and assignee write nothing.
   * The assignee must be an Admin or Super Admin.
   */
  updateTicketStatus(
    id: string,
    status: TicketStatusValue,
    changedByUserId: string,
    assignedToUserId?: string,
  ): Promise<SupportTicket>;

  // Replies
  /**
   * Inserts the reply; when `staffReply` and the ticket is open, also moves it
   * to in_progress with a status-history row - all in one transaction.
   */
  addReply(reply: Omit<TicketReply, "id" | "repliedAt">, options: { staffReply: boolean }): Promise<TicketReply>;
  getRepliesByTicket(ticketId: string, includeInternal?: boolean): Promise<TicketReply[]>;

  // Notifications
  /** The recipient must exist (SupportRuleError RECIPIENT_NOT_FOUND). */
  /** With `actorUserId` (a staff send) the insert and its SEND_NOTIFICATION audit row are one transaction. */
  createNotification(notif: Omit<InAppNotification, "id" | "createdAt">, actorUserId?: string): Promise<InAppNotification>;
  /**
   * One notification for every non-deleted user holding one of the audience
   * roles, written in a single statement together with its audit record.
   */
  broadcastNotification(
    audience: BroadcastAudience,
    notif: Omit<InAppNotification, "id" | "createdAt" | "recipientUserId">,
    actorUserId: string,
  ): Promise<{ recipientCount: number }>;
  getNotificationsByUser(userId: string): Promise<InAppNotification[]>;
  /** False when the notification does not exist or belongs to someone else. */
  markNotificationAsRead(id: string, userId: string): Promise<boolean>;
  markAllNotificationsAsRead(userId: string): Promise<void>;

  // Audit Logs
  createAuditLog(log: Omit<AuditLogEntry, "id" | "createdAt">): Promise<AuditLogEntry>;
  getAuditLogs(limit?: number): Promise<AuditLogEntry[]>;

  // System Settings
  getSettings(): Promise<SystemSetting[]>;
  getSettingByKey(key: string): Promise<SystemSetting | null>;
  /** Updates an existing key only (RecordNotFoundError otherwise), audited in the same transaction. */
  updateSetting(key: string, value: string, updatedByUserId: string): Promise<SystemSetting>;
}
