/**
 * Live schema: every id here is a database-generated identity
 * (NXA_SupportTickets.SupportTicketId, NXA_TicketReplies.TicketReplyId,
 * NXA_Notifications.NotificationId, NXA_AuditLogs.AuditLogId: BIGINT;
 * NXA_SupportTicketCategories.SupportTicketCategoryId: INT). Ids are never
 * generated by the application and never sent as GUIDs.
 */
const isId = (id: string | undefined | null): id is string => typeof id === "string" && /^\d{1,19}$/.test(id);
const isIntId = (id: string | undefined | null): id is string => typeof id === "string" && /^\d{1,9}$/.test(id);
const iso = (d: Date | string | null | undefined): string | undefined => (d ? new Date(d).toISOString() : undefined);

const errorNumber = (err: unknown): number | undefined => {
  const e = err as { number?: number; originalError?: { info?: { number?: number } } };
  return e?.number ?? e?.originalError?.info?.number;
};

const TICKET_SELECT = `
  SELECT t.SupportTicketId, t.TicketNumber, t.StudentUserId, us.FullName AS StudentName,
         t.CategoryId, c.CategoryName, t.Subject, t.Description, t.Priority, t.TicketStatus,
         t.AssignedToUserId, ua.FullName AS AssignedToName, t.CreatedAt, t.ClosedAt
  FROM dbo.NXA_SupportTickets t
  LEFT JOIN dbo.NXA_SupportTicketCategories c ON c.SupportTicketCategoryId = t.CategoryId
  LEFT JOIN dbo.NXA_Users us ON t.StudentUserId = us.UserId
  LEFT JOIN dbo.NXA_Users ua ON t.AssignedToUserId = ua.UserId
`;

/* eslint-disable @typescript-eslint/no-explicit-any */
const toTicket = (r: any): SupportTicket => ({
  id: String(r.SupportTicketId),
  ticketNumber: r.TicketNumber,
  studentUserId: String(r.StudentUserId),
  studentName: r.StudentName ?? undefined,
  categoryId: String(r.CategoryId),
  categoryName: r.CategoryName ?? undefined,
  subject: r.Subject,
  description: r.Description,
  priority: String(r.Priority ?? "").toLowerCase() as SupportTicket["priority"],
  ticketStatus: String(r.TicketStatus ?? "").toLowerCase() as SupportTicket["ticketStatus"],
  assignedToUserId: r.AssignedToUserId != null ? String(r.AssignedToUserId) : undefined,
  assignedToName: r.AssignedToName ?? undefined,
  createdAt: iso(r.CreatedAt) ?? "",
  closedAt: iso(r.ClosedAt),
});

const toMessage = (r: any): DirectMessage => ({
  id: String(r.MessageId),
  senderUserId: String(r.SenderUserId),
  recipientUserId: String(r.RecipientUserId),
  body: r.MessageBody,
  sentAt: iso(r.SentAt)!,
  ...(r.ReadAt ? { readAt: iso(r.ReadAt) } : {}),
});

const toNotification = (r: any): InAppNotification => ({
  id: String(r.NotificationId),
  recipientUserId: String(r.RecipientUserId),
  notificationType: r.NotificationType,
  title: r.Title,
  messageBody: r.MessageBody,
  priority: String(r.Priority ?? "").toLowerCase() as InAppNotification["priority"],
  readAt: iso(r.ReadAt),
  createdAt: iso(r.CreatedAt) ?? "",
  relatedEntityId: r.RelatedEntityId != null ? String(r.RelatedEntityId) : undefined,
  relatedEntityType: r.RelatedEntityType ?? undefined,
});

const toSetting = (r: any, maskSecret: boolean): SystemSetting => ({
  id: String(r.InstituteSettingId),
  settingKey: r.SettingKey,
  settingValue: maskSecret && r.IsSecret ? "********" : r.SettingValue,
  valueType: r.ValueType,
  isSecret: Boolean(r.IsSecret),
  updatedByUserId: r.UpdatedByUserId != null ? String(r.UpdatedByUserId) : undefined,
  updatedAt: iso(r.UpdatedAt) ?? "",
});
