  async updateSetting(key: string, value: string, updatedByUserId: string): Promise<SystemSetting> {
    await this.inTransaction(async (tx) => {
      const cur = tx.request();
      cur.input("SettingKey", sql.VarChar(150), key);
      const before = await cur.query<{ SettingValue: string | null; IsSecret: boolean }>(
        `SELECT SettingValue, IsSecret FROM dbo.NXA_InstituteSettings WITH (UPDLOCK, HOLDLOCK) WHERE SettingKey = @SettingKey`,
      );
      const row = before.recordset[0];
      // Only existing keys are updated: no key is invented.
      if (!row) throw new RecordNotFoundError("setting", key);
      if (row.SettingValue === value) return; // no-op

      const upd = tx.request();
      upd.input("SettingKey", sql.VarChar(150), key);
      upd.input("SettingValue", sql.NVarChar(sql.MAX), value);
      upd.input("UpdatedBy", sql.BigInt, isId(updatedByUserId) ? updatedByUserId : null);
      await upd.query(`
        UPDATE dbo.NXA_InstituteSettings
        SET SettingValue = @SettingValue, UpdatedByUserId = @UpdatedBy, UpdatedAt = SYSUTCDATETIME()
        WHERE SettingKey = @SettingKey
      `);

      const mask = (v: string | null) => (row.IsSecret ? "********" : v);
      await writeAuditLog(tx.request(), {
        actorUserId: updatedByUserId,
        actionType: "UPDATE_SETTING",
        moduleCode: "INSTITUTE_SETTINGS",
        entityName: "InstituteSetting",
        entityId: key,
        oldValues: JSON.stringify({ [key]: mask(row.SettingValue) }),
        newValues: JSON.stringify({ [key]: mask(value) }),
      });
    });
    const updated = await this.getSettingByKey(key);
    if (!updated) throw new RecordNotFoundError("setting", key);
    return updated;
  }
